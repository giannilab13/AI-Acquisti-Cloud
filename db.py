def create_company(name, vat_number="", sector=""):
    name = str(name or "").strip()
    vat_number = str(vat_number or "").strip().upper()
    sector = str(sector or "").strip()

    if not name:
        raise ValueError("Inserisci il nome dell'azienda.")

    conn = get_platform_connection()
    try:
        if vat_number:
            existing = conn.execute(
                "SELECT id,name FROM companies WHERE UPPER(vat_number)=UPPER(?)",
                (vat_number,),
            ).fetchone()
            if existing:
                raise ValueError(
                    f"Esiste già un'azienda con questa P.IVA: {existing['name']}."
                )

        base_slug = _slugify(name)
        slug = base_slug
        n = 2
        while conn.execute("SELECT 1 FROM companies WHERE slug=?", (slug,)).fetchone():
            slug = f"{base_slug}-{n}"
            n += 1

        cur = conn.execute(
            """
            INSERT INTO companies(name,vat_number,sector,slug)
            VALUES(?,?,?,?)
            """,
            (name, vat_number or None, sector or None, slug),
        )
        company_id = cur.lastrowid
        conn.commit()
    finally:
        conn.close()

    init_company_db(company_id)
    return get_company(company_id)


