def _translate_sql(query):
    """Adatta la sintassi SQLite usata dalla baseline alla sintassi PostgreSQL."""
    q = str(query)
    had_insert_ignore = bool(
        re.search(r"\bINSERT\s+OR\s+IGNORE\s+INTO\b", q, flags=re.I)
    )
    if had_insert_ignore:
        q = re.sub(
            r"\bINSERT\s+OR\s+IGNORE\s+INTO\b",
            "INSERT INTO",
            q,
            count=1,
            flags=re.I,
        )

    # La baseline usa campi timestamp come testo.
    q = re.sub(
        r"\bCURRENT_TIMESTAMP\b(?!\s*::)",
        "CURRENT_TIMESTAMP::TEXT",
        q,
        flags=re.I,
    )

    # Placeholder sqlite -> psycopg.
    q = q.replace("?", "%s")

    # SQLite INSERT OR IGNORE -> PostgreSQL ON CONFLICT DO NOTHING.
    if had_insert_ignore and "ON CONFLICT" not in q.upper():
        q = q.rstrip().rstrip(";") + " ON CONFLICT DO NOTHING"

    return q


def _insert_table_name(query):
    match = re.match(
        r"\s*INSERT\s+(?:OR\s+IGNORE\s+)?INTO\s+([A-Za-z_][A-Za-z0-9_]*)",
        str(query),
        flags=re.I,
    )
    return match.group(1).lower() if match else None


class CursorCompat:
    def __init__(self, cursor):
        self._cursor = cursor
        self.lastrowid = None

    @property
    def rowcount(self):
        return self._cursor.rowcount

    def execute(self, query, params=()):
        original = str(query)
        translated = _translate_sql(original)
        table = _insert_table_name(original)

        wants_returning_id = (
            table in IDENTITY_TABLES
            and "RETURNING" not in translated.upper()
        )
        if wants_returning_id:
            translated = translated.rstrip().rstrip(";") + " RETURNING id"

        self._cursor.execute(translated, params or ())
        self.lastrowid = None

        if wants_returning_id:
            row = self._cursor.fetchone()
            if row:
                self.lastrowid = row.get("id") if isinstance(row, dict) else row[0]

        return self

    def fetchone(self):
        return self._cursor.fetchone()

    def fetchall(self):
        return self._cursor.fetchall()

    def close(self):
        self._cursor.close()


class ConnectionCompat:
    def __init__(self, raw):
        self._raw = raw

    def cursor(self):
        return CursorCompat(self._raw.cursor())

    def execute(self, query, params=()):
        cur = self.cursor()
        return cur.execute(query, params)

    def commit(self):
        self._raw.commit()

    def rollback(self):
        self._raw.rollback()

    def close(self):
        self._raw.close()


