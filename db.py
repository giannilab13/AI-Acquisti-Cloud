def init_company_db(company_id):
    company_id = int(company_id)
    schema_name = company_schema_name(company_id)

    if company_id in _initialized_companies:
        return

    raw = _raw_connection()
    try:
        with raw.cursor() as cur:
            cur.execute(
                sql.SQL("CREATE SCHEMA IF NOT EXISTS {}").format(
                    sql.Identifier(schema_name)
                )
            )
        _set_search_path(raw, schema_name)
        with raw.cursor() as cur:
            cur.execute(COMPANY_DDL)
        _ensure_numeric_columns(raw, schema_name)
        raw.commit()
        _initialized_companies.add(company_id)
    except Exception:
        raw.rollback()
        raise
    finally:
        raw.close()


def get_connection(company_id=None):
    company_id = int(company_id or get_active_company_id())
    if not get_company(company_id):
        raise RuntimeError("Azienda non valida o non attiva.")

    init_company_db(company_id)
    raw = _raw_connection()
    _set_search_path(raw, company_schema_name(company_id))
    return ConnectionCompat(raw)


def next_text_id(conn, table, prefix):
    # table e prefix sono controllati dal codice applicativo, non dall'utente.
    rows = conn.execute(
        f"SELECT id FROM {table} WHERE id LIKE ?",
        (f"{prefix}%",),
    ).fetchall()
    nums = []
    for row in rows:
        try:
            nums.append(int(row["id"][len(prefix):]))
        except Exception:
            pass
    return f"{prefix}{(max(nums) if nums else 0) + 1:04d}"
